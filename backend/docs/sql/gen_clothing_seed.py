PROD_SPEC = json.dumps(
    [{"key": "颜色", "valueList": ["红色", "蓝色", "黑色", "白色", "灰色"]},
     {"key": "尺寸", "valueList": ["S", "M", "L", "XL"]}],
    ensure_ascii=False)

SLIDER = "/images/product/cloth_slider1.jpg,/images/product/cloth_slider2.jpg,/images/product/cloth_slider3.jpg"
DETAIL = "/images/product/cloth_detail1.jpg,/images/product/cloth_detail2.jpg"


def esc(s):
    return s.replace("'", "\\'")


def main():
    lines = []
    lines.append("SET NAMES utf8mb4;")
    lines.append("SET FOREIGN_KEY_CHECKS=0;")
    lines.append("")
    pid = 9001
    skid = 900001
    prod_vals = []
    sku_vals = []
    detail_vals = []
    for name, brand, c2, c3, skus in ITEMS:
        bid = BRAND[brand]
        # product
        prod_vals.append(
            f"({pid},'{esc(name)}',{bid},2,{c2},{c3},'件','{SLIDER}',"
            f"'{esc(PROD_SPEC)}',1,1,'审核通过','{brand}','服装服饰','','','{DETAIL}',NOW(),NOW(),0)")
        # details
        detail_vals.append(f"({pid},{pid},'{DETAIL}',NOW(),NOW(),0)")
        for (color, size, sale, market, stock, salenum) in skus:
            sku_name = f"{name} {color} {size}"
            sku_spec = json.dumps({"颜色": color, "尺寸": size}, ensure_ascii=False)
            sku_vals.append(
                f"({skid},'SKU{skid}','{esc(sku_name)}',{pid},'/images/product/sku_{skid}.jpg',"
                f"{sale},{market},{market*0.6:.0f},{stock},{salenum},"
                f"'{esc(sku_spec)}','0.3kg','2L',1,'{esc(name)}','{brand}',2,{c2},{c3},{bid},NOW(),NOW(),0)")
            skid += 1
        pid += 1

    lines.append("-- 商品（服装服饰 category1_id=2）")
    lines.append("INSERT INTO product (id,name,brand_id,category1_id,category2_id,category3_id,"
                 "unit_name,slider_urls,spec_value,status,audit_status,audit_message,"
                 "brand_name,category1_name,category2_name,category3_name,details_image_urls,create_time,update_time,is_deleted) VALUES")
    lines.append(",\n".join(prod_vals) + ";")
    lines.append("")
    lines.append("-- 商品SKU")
    lines.append("INSERT INTO product_sku (id,sku_code,sku_name,product_id,thumb_img,sale_price,market_price,"
                 "cost_price,stock_num,sale_num,sku_spec,weight,volume,status,product_name,brand_name,"
                 "category1_id,category2_id,category3_id,brand_id,create_time,update_time,is_deleted) VALUES")
    lines.append(",\n".join(sku_vals) + ";")
    lines.append("")
    lines.append("-- 商品详情")
    lines.append("INSERT INTO product_details (id,product_id,image_urls,create_time,update_time,is_deleted) VALUES")
    lines.append(",\n".join(detail_vals) + ";")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
